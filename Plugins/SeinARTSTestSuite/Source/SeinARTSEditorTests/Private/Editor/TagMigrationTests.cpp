	const auto NewSupport = Manager.RequestGameplayTag(FName(*(Destination + TEXT(".Support"))));
	const auto NewRadio = Manager.RequestGameplayTag(FName(*(Destination + TEXT(".Support.Radio"))));
	ASSERT_THAT(IsTrue(NewRadio.MatchesTag(NewSupport)));
	ASSERT_THAT(IsTrue(NewRadio.MatchesTag(Result.DerivedTag)));
	ASSERT_THAT(IsTrue(CastChecked<USeinAbility>(ChildBP->GeneratedClass->GetDefaultObject())->AbilityTag == NewOfficer));
	const auto* After = Table->FindRow<FSeinTagLifecycleTestRow>(TEXT("Row"), TEXT("HierarchyMigrationTest"));
