	ASSERT_THAT(IsTrue(After->Tag == NewSupport));
	ASSERT_THAT(IsTrue(After->Tags.HasTagExact(NewRadio)));
	ASSERT_THAT(IsTrue(After->Query.Matches(After->Tags)));
