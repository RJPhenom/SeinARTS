	ASSERT_THAT(AreEqual(3, After->Map.FindRef(NewSupport)));
	ASSERT_THAT(IsTrue(After->Payload.Get<FSeinIdentityPayload>().IdentityTag == NewOfficer));
	ASSERT_THAT(IsFalse(Manager.FindTagNode(NewSupport)->IsExplicitTag()));
	ASSERT_THAT(IsTrue(Manager.RequestGameplayTag(Outside.GetTagName()) == Outside));
	// A second rename must keep every original root/child/intermediate alias resolving directly.
	Fixture.MarkClean();
	const FString FinalRoot = Fixture.TagRoot + TEXT(".Veteran");
	const auto Again = SeinAutoTag::RenameAssetTag(BP, FName(*FinalRoot));
	ASSERT_THAT(IsTrue(Again.WasUpdated()));
	Manager.EditorRefreshGameplayTagTree();
	for (const auto& Pair : TArray<TPair<FGameplayTag, FString>>{
		{Root, TEXT("")}, {Officer, TEXT(".Officer")}, {Implicit, TEXT(".Support")}, {Radio, TEXT(".Support.Radio")}})
	{
		const FName Expected(*(FinalRoot + Pair.Value));
		ASSERT_THAT(IsTrue(Manager.RequestGameplayTag(Pair.Key.GetTagName()).GetTagName() == Expected));
		const auto* Source = Manager.FindTagSource(Fixture.SourceName);
		ASSERT_THAT(IsTrue(Source->SourceTagList->GameplayTagRedirects.ContainsByPredicate(
			[&Pair, Expected](const auto& Redirect) { return Redirect.OldTagName == Pair.Key.GetTagName() && Redirect.NewTagName == Expected; })));
	}
