	Row.Tag = Implicit;
	Row.Tags.AddTag(Radio);
	Row.Query = FGameplayTagQuery::MakeQuery_MatchTag(Root);
	Row.Map.Add(Root, 1);
	Row.Map.Add(Officer, 2);
	Row.Map.Add(Implicit, 3);
	Row.Payload.InitializeAs<FSeinIdentityPayload>();
	Row.Payload.GetMutable<FSeinIdentityPayload>().IdentityTag = Officer;
	Table->AddRow(TEXT("Row"), Row);
