bool SeinTagAudit::IsRedirectEndpoint(FName Tag)
{
	auto Contains = [Tag](const UGameplayTagsList* List)
	{
		if (List) for (const FGameplayTagRedirect& Redirect : List->GameplayTagRedirects)
			if (Redirect.OldTagName == Tag || Redirect.NewTagName == Tag) return true;
		return false;
	};
	if (Contains(GetDefault<UGameplayTagsSettings>())) return true;
	for (const auto* Source : TagSources()) if (Contains(Source->SourceTagList)) return true;
	return false;
}

FString SeinTagAudit::MutationBlocker()
{
	if (GEditor && GEditor->PlayWorld) return TEXT("Stop Play in Editor first.");
	auto& Registry = FModuleManager::LoadModuleChecked<FAssetRegistryModule>("AssetRegistry").Get();
	if (Registry.IsLoadingAssets()) return TEXT("Wait for asset discovery to complete.");
	for (TObjectIterator<UPackage> It; It; ++It)
	{
		if (!IsValid(*It)) continue;
		const FString Name = It->GetName();
		if (It->IsDirty() && !It->HasAnyPackageFlags(PKG_CompiledIn) && !It->HasAnyFlags(RF_Transient)
			&& !Name.StartsWith(TEXT("/Temp/")) && !Name.StartsWith(TEXT("/Memory/"))
			&& *It != GetTransientPackage())
			return FString::Printf(TEXT("Save content first: %s has unsaved changes."), *Name);
	}
	return FString();
}

static TArray<FSeinTagAuditRow> InspectSource(FName SourceName)
{
	using namespace SeinTagAudit;
	TArray<FSeinTagAuditRow> Rows;
	auto& Manager = UGameplayTagsManager::Get();
	const auto* Source = Manager.FindTagSource(SourceName);
	if (!Source || !Source->SourceTagList) return Rows;
	const FString Blocker = MutationBlocker();
	const bool bSourceCurrent = SeinTagSourcePersistence::MatchesDisk(Source->SourceTagList->ConfigFileName, Source->SourceTagList);
	const bool bWritable = !IFileManager::Get().IsReadOnly(*Source->SourceTagList->ConfigFileName);
	TArray<TSharedPtr<FGameplayTagNode>> Unused;
	IGameplayTagsEditorModule::Get().GetUnusedGameplayTags(Unused);
	TSet<FName> UnusedNames;
	for (const auto& Node : Unused) if (Node.IsValid()) UnusedNames.Add(Node->GetCompleteTagName());
	auto& Registry = FModuleManager::LoadModuleChecked<FAssetRegistryModule>("AssetRegistry").Get();
	FARFilter Filter;
	Filter.ClassPaths.Add(UBlueprint::StaticClass()->GetClassPathName());
	Filter.bRecursiveClasses = true;
	TArray<FAssetData> Assets;
	Registry.GetAssets(Filter, Assets);
	// Native code/string-based requests are not searchable-name dependencies. Conservative text
	// matching intentionally retains comments and ancestor references rather than guessing intent.
	TArray<TPair<FString, FString>> TextSources;
	bool bReadFailed = false;
	for (const FString Root : {(FPaths::ProjectDir() / TEXT("Source")), FPaths::ProjectConfigDir(), FPaths::ProjectPluginsDir()})
	{
		TArray<FString> Files;
		IFileManager::Get().FindFilesRecursive(Files, *Root, TEXT("*"), true, false);
		for (const FString& File : Files)
		{
			const FString Extension = FPaths::GetExtension(File);
			if (File.Contains(TEXT("/Intermediate/")) || File.Contains(TEXT("/Binaries/"))
				|| FPaths::GetCleanFilename(File) == SourceName.ToString()) continue;
			if (Extension != TEXT("cpp") && Extension != TEXT("h") && Extension != TEXT("ini")) continue;
			FString Text;
			if (!FFileHelper::LoadFileToString(Text, *File)) { bReadFailed = true; continue; }
			TextSources.Emplace(File, MoveTemp(Text));
		}
	}
	for (const auto& Entry : Source->SourceTagList->GameplayTagList)
	{
		FSeinTagAuditRow Row;
		Row.Tag = Entry.Tag;
		const FGameplayTag Tag = Manager.RequestGameplayTag(Entry.Tag, false);
		for (const FAssetData& Asset : Assets)
		{
			FGameplayTag Identity;
			bool bGenerated = false;
			if (const auto* BP = Cast<UBlueprint>(Asset.FastGetAsset(false)))
			{
				if (SeinAutoTag::ReadAssetIdentity(BP, Identity, bGenerated) && Identity == Tag)
					Row.Owners.Add(Asset.PackageName.ToString());
			}
			else for (const FName Key : {SeinAssetTagKeys::AbilityTag(), SeinAssetTagKeys::EffectTag(), SeinAssetTagKeys::IdentityTag()})
			{
				FString Value;
				if (Asset.GetTagValue(Key, Value) && FName(*Value) == Entry.Tag)
					Row.Owners.AddUnique(Asset.PackageName.ToString());
			}
		}
		FString Comment;
		TArray<FName> Sources;
		bool bExplicit = false, bRestricted = false, bAllowChildren = false;
		Manager.GetTagEditorData(Entry.Tag, Comment, Sources, bExplicit, bRestricted, bAllowChildren);
		if (!Blocker.IsEmpty()) Row.Reason = Blocker;
		else if (!bSourceCurrent) Row.Reason = TEXT("Tag source differs from disk; refresh its dictionary before cleanup.");
		else if (!bWritable) Row.Reason = TEXT("Generated tag source is read-only.");
		else if (bReadFailed) Row.Reason = TEXT("A source/config file could not be inspected.");
		else if (!Row.Owners.IsEmpty()) Row.Reason = Row.Owners.Num() > 1 ? TEXT("Duplicate identity owners; resolve explicitly.") : TEXT("Owned by an asset.");
		else if (!Entry.DevComment.StartsWith(TEXT("Auto-generated by SeinARTS"))) Row.Reason = TEXT("No generated provenance; retained as authored data.");
		else if (Sources.Num() != 1 || Sources[0] != SourceName || bRestricted) Row.Reason = TEXT("Shared/native/restricted source; retained.");
		else if (IsRedirectEndpoint(Entry.Tag)) Row.Reason = TEXT("Compatibility redirect endpoint; retained.");
		else if (!Manager.RequestGameplayTagChildren(Tag).IsEmpty()) Row.Reason = TEXT("Has descendant tags; hierarchy retained.");
		else if (!UnusedNames.Contains(Entry.Tag)) Row.Reason = TEXT("Referenced by saved assets or configuration.");
		else
		{
			TArray<FString> RemovedNames{Entry.Tag.ToString()};
			// Only implicit ancestors whose sole child is this chain disappear with the leaf.
			FString Parent = Entry.Tag.ToString();
			int32 Dot = INDEX_NONE;
			while (Parent.FindLastChar(TEXT('.'), Dot))
			{
				Parent.LeftInline(Dot);
				const auto ParentNode = Manager.FindTagNode(FName(*Parent));
				if (!ParentNode.IsValid() || ParentNode->IsExplicitTag() || ParentNode->GetChildTagNodes().Num() != 1) break;
				RemovedNames.Add(Parent);
				if (IsRedirectEndpoint(FName(*Parent))) Row.Reason = TEXT("Removing this leaf would remove a redirected implicit parent.");
			}
			for (const auto& Text : TextSources)
				if (RemovedNames.ContainsByPredicate([&Text](const FString& Name) { return Text.Value.Contains(Name); }))
				{
					Row.Reason = TEXT("Source/config reference: ") + Text.Key;
					break;
				}
			if (Row.Reason.IsEmpty()) { Row.bCanDelete = true; Row.Reason = TEXT("Unused generated leaf; eligible for cleanup."); }
		}
		Row.Owners.Sort();
		Rows.Add(MoveTemp(Row));
	}
	Rows.Sort([](const auto& A, const auto& B) { return A.Tag.ToString() < B.Tag.ToString(); });
	return Rows;
}

TArray<FSeinTagAuditRow> SeinTagAudit::Inspect()
{
	return InspectSource(GeneratedSource);
}

