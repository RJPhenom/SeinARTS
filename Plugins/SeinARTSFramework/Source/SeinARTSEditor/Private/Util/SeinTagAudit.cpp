FString SeinTagAudit::Format(const TArray<FSeinTagAuditRow>& Rows)
{
	FString Text = TEXT("Generated tag audit\n\n");
	for (const auto& Row : Rows)
	{
		Text += Row.Tag.ToString() + TEXT(" — ") + Row.Reason + TEXT("\n");
		for (const auto& Owner : Row.Owners) Text += TEXT("  ") + Owner + TEXT("\n");
	}
	return Text;
}

static FString CleanupSource(FName SourceName, const TArray<FName>& Candidates)
{
	using namespace SeinTagAudit;
	FString Receipt;
	bool bRemoved = false;
	for (FName Candidate : Candidates)
	{
		// Refresh the whole evidence set per deletion; callers cannot reuse a stale approval/report.
		const auto Rows = InspectSource(SourceName);
		const auto* Row = Rows.FindByPredicate([Candidate](const auto& R) { return R.Tag == Candidate; });
		if (!Row || !Row->bCanDelete)
		{
			Receipt += Candidate.ToString() + TEXT(": retained — ") + (Row ? Row->Reason : TEXT("not a generated entry")) + TEXT("\n");
			continue;
		}
		const auto* Source = UGameplayTagsManager::Get().FindTagSource(SourceName);
		if (!Source || !Source->SourceTagList) continue;
		UGameplayTagsList* SourceList = Source->SourceTagList;
		const FString Path = SourceList->ConfigFileName;
		FString Before, After;
		const FString Section = SourceList->GetClass()->GetPathName();
		auto ExpectedDefinitions = SourceList->GameplayTagList;
		ExpectedDefinitions.RemoveAll([Candidate](const auto& Entry) { return Entry.Tag == Candidate; });
		const auto ExpectedRedirects = SourceList->GameplayTagRedirects;
		if (!FFileHelper::LoadFileToString(Before, *Path) || !SeinTagSourcePersistence::MatchesDisk(Path, SourceList))
		{
			Receipt += Candidate.ToString() + TEXT(": source could not be read; retained\n");
			continue;
		}
		bool bDeleted = IGameplayTagsEditorModule::Get().DeleteTagFromINI(UGameplayTagsManager::Get().FindTagNode(Candidate));
		bDeleted = bDeleted && SeinTagSourcePersistence::MatchesDisk(Path, Section, ExpectedDefinitions, ExpectedRedirects);
		if (!bDeleted)
		{
			const bool bRestored = FFileHelper::SaveStringToFile(Before, *Path)
				&& FFileHelper::LoadFileToString(After, *Path) && After == Before;
			GConfig->LoadFile(Path);
			SourceList->ReloadConfig(nullptr, *Path);
			UGameplayTagsManager::Get().EditorRefreshGameplayTagTree();
			if (!bRestored)
			{
				Receipt += Candidate.ToString() + TEXT(": source restoration failed; restore the INI from source control before continuing.\n");
				break;
			}
		}
		bRemoved |= bDeleted;
		Receipt += Candidate.ToString() + (bDeleted ? TEXT(": removed\n") : TEXT(": deletion refused\n"));
	}
	if (bRemoved && GEditor) GEditor->ResetTransaction(FText::FromString(TEXT("Generated tag cleanup")));
	return Receipt.IsEmpty() ? TEXT("No eligible generated tags to remove.") : Receipt;
}

FString SeinTagAudit::Cleanup(const TArray<FName>& Candidates)
{
	return CleanupSource(GeneratedSource, Candidates);
}

