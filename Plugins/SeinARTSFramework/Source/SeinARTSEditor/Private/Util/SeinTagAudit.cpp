void SeinTagAudit::ShowWindow()
{
	const auto Report = SNew(STextBlock).Text(FText::FromString(Format(Inspect())));
	const auto Window = SNew(SWindow).Title(FText::FromString(TEXT("Generated Tags")))
		.ClientSize(FVector2D(1000, 650))
		[
			SNew(SVerticalBox)
			+ SVerticalBox::Slot().FillHeight(1).Padding(12)
			[SNew(SScrollBox) + SScrollBox::Slot()[Report]]
			+ SVerticalBox::Slot().AutoHeight().Padding(12)
			[SNew(SHorizontalBox)
				+ SHorizontalBox::Slot().AutoWidth()
				[SNew(SButton).Text(FText::FromString(TEXT("Refresh")))
					.OnClicked_Lambda([Report]() { Report->SetText(FText::FromString(Format(Inspect()))); return FReply::Handled(); })]
				+ SHorizontalBox::Slot().AutoWidth().Padding(12, 0)
				[SNew(SButton).Text(FText::FromString(TEXT("Clean Up Unused Generated Tags")))
					.OnClicked_Lambda([Report]()
					{
						TArray<FName> Candidates;
						FString Preview = TEXT("Remove these unused generated tags from the dictionary? This clears editor undo history so an undo cannot restore a reference to a removed tag.\n\n");
						for (const auto& Row : Inspect()) if (Row.bCanDelete) { Candidates.Add(Row.Tag); Preview += Row.Tag.ToString() + TEXT("\n"); }
						if (Candidates.IsEmpty()) FMessageDialog::Open(EAppMsgType::Ok, FText::FromString(TEXT("No eligible tags. Save content and refresh to see why entries are retained.")));
						else if (FMessageDialog::Open(EAppMsgType::YesNo, FText::FromString(Preview)) == EAppReturnType::Yes)
							FMessageDialog::Open(EAppMsgType::Ok, FText::FromString(Cleanup(Candidates)));
						Report->SetText(FText::FromString(Format(Inspect())));
						return FReply::Handled();
					})]
			]
		];
	FSlateApplication::Get().AddWindow(Window);
}
