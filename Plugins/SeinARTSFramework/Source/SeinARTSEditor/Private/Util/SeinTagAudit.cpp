FString SeinTagAudit::CleanupForAutomation(FName SourceName, const TArray<FName>& Candidates)
{
	if (!SourceName.ToString().StartsWith(TEXT("SeinTagTest_"))) return TEXT("Requires an isolated automation source.");
	return CleanupSource(SourceName, Candidates);
}
