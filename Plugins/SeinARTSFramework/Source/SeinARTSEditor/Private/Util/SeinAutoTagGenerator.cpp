/** Dedicated INI source the auto-tag system writes generated tags into.
 *  Lives at `<Project>/Config/Tags/SeinAutoGeneratedTags.ini`. Designers
 *  can open Project Settings → Project → Gameplay Tags and see this as a
 *  separate source alongside their hand-curated `DefaultGameplayTags.ini`.
 *  Cleanup considers only exclusively owned, unused generated entries. */
static const FString GSeinAutoTagSourceName = TEXT("SeinAutoGeneratedTags.ini");

