bool SeinAutoTag::RegenerateAssetTag(
	UBlueprint* OwningBP,
	bool bForceOverManual)
{
	return RegenerateAssetTagDetailed(
		OwningBP, bForceOverManual).WasUpdated();
}

int32 SeinAutoTag::RegenerateAllAssetTags(bool bForceOverManual)
{
	FAssetRegistryModule& AssetRegistryModule =
		FModuleManager::LoadModuleChecked<FAssetRegistryModule>("AssetRegistry");
	IAssetRegistry& AssetRegistry = AssetRegistryModule.Get();

	TArray<FAssetData> Candidates;
	FARFilter Filter;
	Filter.bRecursiveClasses = true;
	Filter.ClassPaths.Add(UBlueprint::StaticClass()->GetClassPathName());
	AssetRegistry.GetAssets(Filter, Candidates);

	// Batch tag-tree refresh. AddNewGameplayTagToINI inside Derive triggers
	// an EditorRefreshGameplayTagTree per call (destroy + reload + reconstruct
	// the full tag tree from all sources). For a sweep over N assets that's
	// O(N) refreshes — each linear in total tag count. Suspending the refresh
	// collapses the whole sweep into one final refresh at Resume time.
	UGameplayTagsManager& Manager = UGameplayTagsManager::Get();
	const FGuid SuspendToken = FGuid::NewGuid();
	Manager.SuspendEditorRefreshGameplayTagTree(SuspendToken);

	int32 NumChanged = 0;
	int32 NumScanned = 0;
	int32 NumTaggableCandidates = 0;
	TArray<TWeakObjectPtr<UBlueprint>> DeferredAfterRefresh;
	for (const FAssetData& Asset : Candidates)
	{
		++NumScanned;
		const FString ParentClass = Asset.GetTagValueRef<FString>(FBlueprintTags::ParentClassPath);
		if (ParentClass.IsEmpty()) continue;
		const bool bIsSeinTaggable =
			ParentClass.Contains(TEXT("SeinAbility")) ||
			ParentClass.Contains(TEXT("SeinEffect")) ||
			ParentClass.Contains(TEXT("SeinActor"));
		if (!bIsSeinTaggable) continue;
		++NumTaggableCandidates;

		UBlueprint* BP = Cast<UBlueprint>(Asset.GetAsset());
		if (!BP) continue;
		const FSeinAutoTagRegenerationResult Result =
			RegenerateAssetTagDetailed(BP, bForceOverManual);
		if (Result.WasUpdated())
		{
			++NumChanged;
		}
		else if (Result.Outcome ==
			ESeinAutoTagRegenerationOutcome::TagDerivationFailed)
		{
			// A missing tag is written while tree refresh is suspended, so
			// its FGameplayTag becomes available only after Resume. Unmapped
			// names can also land here; the second pass remains a no-op.
			DeferredAfterRefresh.Add(BP);
		}
	}

	Manager.ResumeEditorRefreshGameplayTagTree(SuspendToken);
	for (const TWeakObjectPtr<UBlueprint>& WeakBP : DeferredAfterRefresh)
	{
		if (UBlueprint* BP = WeakBP.Get())
		{
			if (RegenerateAssetTagDetailed(
					BP, bForceOverManual).WasUpdated())
			{
				++NumChanged;
			}
		}
	}

	UE_LOG(LogSeinAutoTagGen, Log,
		TEXT("RegenerateAllAssetTags (force=%d): scanned %d BP(s), %d Sein-taggable, %d updated."),
		bForceOverManual ? 1 : 0, NumScanned, NumTaggableCandidates, NumChanged);
	return NumChanged;
}

