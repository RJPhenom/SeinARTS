	/** Split an asset name on `_`. First segment is the prefix; rest is the
	 *  name body. Returns false if there's no `_` in the name. */
	static bool SplitOnUnderscore(const FString& AssetName, FString& OutPrefix, TArray<FString>& OutNameSegments)
	{
		TArray<FString> AllSegments;
		AssetName.ParseIntoArray(AllSegments, TEXT("_"), /*InCullEmpty*/ false);
		if (AllSegments.Num() < 2) return false;
		OutPrefix = AllSegments[0];
		OutNameSegments.Reset(AllSegments.Num() - 1);
		for (int32 i = 1; i < AllSegments.Num(); ++i)
		{
			// Skip blank inner segments (e.g. "SA__Move" — defensive).
			if (!AllSegments[i].IsEmpty())
			{
				OutNameSegments.Add(AllSegments[i]);
			}
		}
		return OutNameSegments.Num() > 0;
	}

	/** Strip the trailing "_C" that Blueprint-generated classes carry. */
	static FString StripBlueprintClassSuffix(const FString& Name)
	{
		if (Name.EndsWith(TEXT("_C")))
		{
			return Name.LeftChop(2);
		}
		return Name;
	}

	/** Read the live (in-memory) CDO of a loaded Sein BP and test whether its
	 *  identity tag equals `Tag`. Entity identity comes from its authoring component,
	 *  with a legacy payload fallback only when no authoring component exists.
	 *  Loaded values take precedence over the last saved registry value. */
	static bool CDOHasMatchingTag(const UBlueprint* BP, const FGameplayTag& Tag)
	{
		if (!BP || !BP->GeneratedClass) return false;
		const UObject* CDO = BP->GeneratedClass->GetDefaultObject();
		if (!CDO) return false;

		if (const USeinAbility* Ability = Cast<USeinAbility>(CDO))
		{
			return Ability->AbilityTag == Tag;
		}
		if (const USeinEffect* Effect = Cast<USeinEffect>(CDO))
		{
			return Effect->EffectTag == Tag;
		}
        FGameplayTag Identity;
        bool bGenerated = false;
        return SeinAutoTag::ReadAssetIdentity(BP, Identity, bGenerated) && Identity == Tag;
	}

