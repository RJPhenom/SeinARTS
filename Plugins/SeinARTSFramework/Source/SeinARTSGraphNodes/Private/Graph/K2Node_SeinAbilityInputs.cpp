void UK2Node_SeinAbilityInputs::ExpandNode(FKismetCompilerContext& Compiler, UEdGraph* Graph)
{
	Super::ExpandNode(Compiler, Graph);
	FString Error;
	if (!FSeinAbilityActivationInputs::ValidateClass(AbilityClass, Error))
	{
		Compiler.MessageLog.Error(*FString::Printf(TEXT("@@: %s"), *Error), this);
		BreakAllNodeLinks();
		return;
	}
	const UEdGraphSchema_K2* Schema = GetDefault<UEdGraphSchema_K2>();
	auto Call = [&](FName Name)
	{
		UK2Node_CallFunction* Node = Compiler.SpawnIntermediateNode<UK2Node_CallFunction>(this, Graph);
		Node->FunctionReference.SetExternalMember(Name, Name == TEXT("SubmitAbility")
			? USeinPlayerAbilityBPFL::StaticClass() : USeinAbilityInputBPFL::StaticClass());
		Node->AllocateDefaultPins();
		if (UEdGraphPin* ClassPin = Node->FindPin(TEXT("AbilityClass"))) ClassPin->DefaultObject = AbilityClass;
		return Node;
	};
	UK2Node_CallFunction* Make = Call(GET_FUNCTION_NAME_CHECKED(USeinAbilityInputBPFL, MakeInputs));
	UEdGraphPin* Values = Make->GetReturnValuePin();
	for (FName Name : AbilityClass->GetDefaultObject<USeinAbility>()->GetActivationInputNames())
	{
		UEdGraphPin* Source = FindPin(InputPin(Name));
		FEdGraphPinType ExpectedType;
		FProperty* Property = FindFProperty<FProperty>(AbilityClass, Name);
		if (!Source || !Schema->ConvertPropertyToPinType(Property, ExpectedType) || Source->PinType != ExpectedType)
		{
			Compiler.MessageLog.Error(TEXT("@@ has stale activation pins. Refresh this node."), this);
			BreakAllNodeLinks();
			return;
		}
		if (Source->LinkedTo.IsEmpty() && !Schema->PinDefaultValueIsEditable(*Source)) continue;
		UK2Node_CallFunction* Set = Call(GET_FUNCTION_NAME_CHECKED(USeinAbilityInputBPFL, SetInput));
		Set->FindPinChecked(TEXT("Name"))->DefaultValue = Name.ToString();
		FGuid CompiledSchema;
		FSeinAbilityActivationInputs::ComputeSchemaDigest(AbilityClass, CompiledSchema, Error);
		TBaseStructure<FGuid>::Get()->ExportText(Set->FindPinChecked(TEXT("CompiledSchema"))->DefaultValue,
			&CompiledSchema, nullptr, nullptr, PPF_None, nullptr);
		UEdGraphPin* Value = Set->FindPinChecked(TEXT("Value"));
		Value->PinType = Source->PinType;
		Compiler.MovePinLinksToIntermediate(*Source, *Value);
		Schema->TryCreateConnection(Values, Set->FindPinChecked(TEXT("Inputs")));
		Values = Set->GetReturnValuePin();
	}
	if (!Operation) Compiler.MovePinLinksToIntermediate(*FindPinChecked(TEXT("ReturnValue")), *Values);
	else
	{
		UK2Node_CallFunction* Submit = Call(Operation == 1
			? GET_FUNCTION_NAME_CHECKED(USeinPlayerAbilityBPFL, SubmitAbility)
			: GET_FUNCTION_NAME_CHECKED(USeinAbilityInputBPFL, IssueAbility));
		Schema->TryCreateConnection(Values, Submit->FindPinChecked(TEXT("Inputs")));
		FGameplayTag Tag = AbilityClass->GetDefaultObject<USeinAbility>()->AbilityTag;
		if (!Tag.IsValid()) Compiler.MessageLog.Error(TEXT("@@ requires an ability with a valid Ability Tag."), this);
		FGameplayTag::StaticStruct()->ExportText(Submit->FindPinChecked(TEXT("AbilityTag"))->DefaultValue,
			&Tag, nullptr, nullptr, PPF_None, nullptr);
		for (const FName Name : {Schema->PN_Execute, Schema->PN_Then, (Operation == 1 ? FName(TEXT("PC")) : FName(TEXT("WorldContextObject"))), FName(TEXT("Entity")),
			FName(TEXT("TargetEntity")), FName(TEXT("TargetLocation")), FName(TEXT("ReturnValue"))})
			Compiler.MovePinLinksToIntermediate(*FindPinChecked(Name), *Submit->FindPinChecked(Name));
	}
	BreakAllNodeLinks();
}

bool UK2Node_SeinAbilityInputs::RefreshInputPins()
{
	if (!AbilityClass) return false;
	AbilityClass = AbilityClass->GetAuthoritativeClass();
	FGuid Current;
	FString Error;
	if (!FSeinAbilityActivationInputs::ComputeSchemaDigest(AbilityClass, Current, Error)) return false;
	if (Current != InputSchema)
	{
		ReconstructNode();
		FBlueprintEditorUtils::MarkBlueprintAsModified(GetBlueprint());
		return true;
	}
	// Default edits do not change the type schema. Update untouched pins while
	// preserving literal overrides entered on the caller.
	bool Changed = false;
	const UEdGraphSchema_K2* Schema = GetDefault<UEdGraphSchema_K2>();
	const USeinAbility* Defaults = AbilityClass->GetDefaultObject<USeinAbility>();
	for (FName Name : Defaults->GetActivationInputNames())
	{
		UEdGraphPin* Pin = FindPin(InputPin(Name));
		FProperty* Property = FindFProperty<FProperty>(AbilityClass, Name);
		FString Value;
		if (!Pin || !Property || !FBlueprintEditorUtils::PropertyValueToString(
			Property, reinterpret_cast<const uint8*>(Defaults), Value, this) || Pin->AutogeneratedDefaultValue == Value) continue;
		const bool UsesDefault = Schema->DoesDefaultValueMatchAutogenerated(*Pin);
		Pin->AutogeneratedDefaultValue = Value;
		if (UsesDefault) Schema->ResetPinToAutogeneratedDefaultValue(Pin, false);
		Changed = true;
	}
	if (Changed)
	{
		GetGraph()->NotifyNodeChanged(this);
		FBlueprintEditorUtils::MarkBlueprintAsModified(GetBlueprint());
	}
	return Changed;
}

