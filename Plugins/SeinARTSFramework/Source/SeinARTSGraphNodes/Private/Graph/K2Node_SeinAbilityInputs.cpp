void UK2Node_SeinAbilityInputs::AllocateDefaultPins()
{
	const UEdGraphSchema_K2* Schema = GetDefault<UEdGraphSchema_K2>();
	if (Operation)
	{
		CreatePin(EGPD_Input, Schema->PC_Exec, Schema->PN_Execute);
		CreatePin(EGPD_Output, Schema->PC_Exec, Schema->PN_Then);
		if (Operation == 1) CreatePin(EGPD_Input, Schema->PC_Object, ASeinPlayerController::StaticClass(), TEXT("PC"));
		else CreatePin(EGPD_Input, Schema->PC_Object, UObject::StaticClass(), TEXT("WorldContextObject"))->bHidden = true;
		CreatePin(EGPD_Input, Schema->PC_Struct, FSeinEntityHandle::StaticStruct(), TEXT("Entity"));
		CreatePin(EGPD_Input, Schema->PC_Struct, FSeinEntityHandle::StaticStruct(), TEXT("TargetEntity"));
		CreatePin(EGPD_Input, Schema->PC_Struct, FFixedVector::StaticStruct(), TEXT("TargetLocation"));
		CreatePin(EGPD_Output, Schema->PC_Boolean, TEXT("ReturnValue"));
	}
	else CreatePin(EGPD_Output, Schema->PC_Struct, FSeinAbilityActivationInputs::StaticStruct(), TEXT("ReturnValue"));
	UEdGraphPin* ClassPin = CreatePin(EGPD_Input, Schema->PC_Class, USeinAbility::StaticClass(), TEXT("AbilityClass"));
	ClassPin->DefaultObject = AbilityClass;
	ClassPin->bNotConnectable = true;
	if (!AbilityClass || !AbilityClass->IsChildOf(USeinAbility::StaticClass())) return;
	FString SchemaError;
	FSeinAbilityActivationInputs::ComputeSchemaDigest(AbilityClass, InputSchema, SchemaError);
	const USeinAbility* Defaults = AbilityClass->GetDefaultObject<USeinAbility>();
	for (FName Name : Defaults->GetActivationInputNames())
	{
		FProperty* Property = FindFProperty<FProperty>(AbilityClass, Name);
		FEdGraphPinType Type;
		if (!Property || !Schema->ConvertPropertyToPinType(Property, Type)) continue;
		UEdGraphPin* Pin = CreatePin(EGPD_Input, Type, InputPin(Name));
		if (UBlueprint* Owner = Cast<UBlueprint>(Property->GetOwnerClass()->ClassGeneratedBy))
			Pin->PersistentGuid = FBlueprintEditorUtils::FindMemberVariableGuidByName(Owner, Name);
		Pin->PinFriendlyName = Property->GetDisplayNameText();
		Pin->PinToolTip = Property->GetToolTipText().ToString();
		FString Default;
		if (FBlueprintEditorUtils::PropertyValueToString(Property, reinterpret_cast<const uint8*>(Defaults), Default, this))
			Schema->SetPinAutogeneratedDefaultValue(Pin, Default);
	}
}

