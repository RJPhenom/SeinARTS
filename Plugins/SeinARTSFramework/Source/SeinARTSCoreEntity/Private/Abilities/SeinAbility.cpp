void USeinAbility::GetAssetRegistryTags(FAssetRegistryTagsContext Context) const
{
	Super::GetAssetRegistryTags(Context);

	// Surface AbilityTag onto the asset's FAssetData so the editor auto-tag
	// collision check reads it without loading this CDO. Bare ToString() form so
	// a string compare against another tag's ToString() is a valid equality test.
	if (AbilityTag.IsValid())
	{
		Context.AddTag(FAssetRegistryTag(
			SeinAssetTagKeys::AbilityTag(),
			AbilityTag.ToString(),
			FAssetRegistryTag::TT_Alphabetical));
	}
}

void USeinAbility::EnqueueProduction(TSubclassOf<ASeinActor> ProducibleClass)
{
	if (!WorldSubsystem)
	{
		UE_LOG(LogSeinAbilityImpl, Warning, TEXT("EnqueueProduction[%s]: ability has no WorldSubsystem"),
			*GetName());
		return;
	}
	if (!ProducibleClass)
	{
		UE_LOG(LogSeinAbilityImpl, Warning, TEXT("EnqueueProduction[%s]: null ProducibleClass"),
			*GetName());
		return;
	}

	FSeinProductionComponent* ProdComp = WorldSubsystem->GetComponent<FSeinProductionComponent>(OwnerEntity);
	if (!ProdComp)
	{
		UE_LOG(LogSeinAbilityImpl, Warning,
			TEXT("EnqueueProduction[%s]: owner %s has no FSeinProductionComponent"),
			*GetName(), *OwnerEntity.ToString());
		return;
	}
	if (!ProdComp->CanQueueMore())
	{
		UE_LOG(LogSeinAbilityImpl, Warning,
			TEXT("EnqueueProduction[%s]: owner %s queue full (max=%d)"),
			*GetName(), *OwnerEntity.ToString(), ProdComp->MaxQueueSize);
		return;
	}

	// Producible's authoring lives on the producible class's entity bridge —
	// FSeinProducibleComponent (BuildTime / RefundPolicy / research metadata)
	// and FSeinIdentityComponent (IdentityTag for the production visual
	// event). Both are FInstancedStruct entries in
	// `USeinEntityComponent::ComponentData` on the BP CDO.
	const FSeinProducibleComponent* Producible = nullptr;
	const FSeinIdentityComponent* Identity = nullptr;
	{
		TArray<const USeinEntityComponent*> Bridges;
		AActor::GetActorClassDefaultComponents<USeinEntityComponent>(ProducibleClass, Bridges);
		for (const USeinEntityComponent* Bridge : Bridges)
		{
			if (!Bridge) continue;
			if (!Producible) Producible = Bridge->FindAuthoredData<FSeinProducibleComponent>();
			if (!Identity)   Identity   = Bridge->FindAuthoredData<FSeinIdentityComponent>();
		}
	}
	if (!Producible)
	{
		UE_LOG(LogSeinAbilityImpl, Warning,
			TEXT("EnqueueProduction[%s]: producible %s has no FSeinProducibleComponent on its entity bridge; skipping"),
			*GetName(), *ProducibleClass->GetName());
		return;
	}

	// Cost split: AtEnqueue bucket was already deducted by the activation gate
	// (recorded as `DeductedCost` on this ability instance). AtCompletion bucket
	// sits in `PendingCompletionCost` waiting to be handed to the queue entry.
	// We snapshot both onto the queue entry: AtEnqueue for refund-on-cancel
	// math, AtCompletion for the production system to deduct at spawn time.
	FSeinProductionQueueEntry Entry;
	Entry.ActorClass = ProducibleClass;
	Entry.TotalBuildTime = Producible->BuildTime;
	Entry.AtEnqueueCost = DeductedCost;
	Entry.AtCompletionCost = PendingCompletionCost;
	Entry.bIsResearch = Producible->bIsResearch;
	Entry.ResearchEffectClass = Producible->GrantedTechEffect;
	Entry.RefundPolicy = Producible->RefundPolicy;

	const bool bWasEmpty = ProdComp->Queue.Num() == 0;
	ProdComp->Queue.Add(MoveTemp(Entry));

	UE_LOG(LogSeinAbilityImpl, Verbose,
		TEXT("EnqueueProduction[%s]: queued %s on %s (build=%.2fs, queue depth=%d)"),
		*GetName(), *ProducibleClass->GetName(), *OwnerEntity.ToString(),
		Producible->BuildTime.ToFloat(), ProdComp->Queue.Num());

	if (bWasEmpty)
	{
		ProdComp->CurrentBuildProgress = FFixedPoint::Zero;
		ProdComp->bStalledAtCompletion = false;
		const FGameplayTag IdentityTag = Identity ? Identity->IdentityTag : FGameplayTag();
		WorldSubsystem->EnqueueVisualEvent(FSeinVisualEvent::MakeProductionEvent(
			OwnerEntity, IdentityTag, /*bCompleted=*/false));
	}
}

void USeinAbility::SetRallyPoint(const FFixedTransform& Transform)
{
	if (!WorldSubsystem) return;
	FSeinProductionComponent* ProdComp = WorldSubsystem->GetComponent<FSeinProductionComponent>(OwnerEntity);
	if (!ProdComp)
	{
		UE_LOG(LogSeinAbilityImpl, Warning,
			TEXT("SetRallyPoint[%s]: owner %s has no FSeinProductionComponent"),
			*GetName(), *OwnerEntity.ToString());
		return;
	}
	ProdComp->bRallyToEntity = false;
	ProdComp->RallyTransform = Transform;
	ProdComp->RallyEntity = FSeinEntityHandle();
}

void USeinAbility::SetRallyEntity(FSeinEntityHandle RallyEntity)
{
	if (!WorldSubsystem) return;
	FSeinProductionComponent* ProdComp = WorldSubsystem->GetComponent<FSeinProductionComponent>(OwnerEntity);
	if (!ProdComp)
	{
		UE_LOG(LogSeinAbilityImpl, Warning,
			TEXT("SetRallyEntity[%s]: owner %s has no FSeinProductionComponent"),
			*GetName(), *OwnerEntity.ToString());
		return;
	}
	ProdComp->bRallyToEntity = true;
	ProdComp->RallyEntity = RallyEntity;
	ProdComp->RallyTransform = FFixedTransform();
}

void USeinAbility::ClearRallyPoint()
{
	if (!WorldSubsystem) return;
	FSeinProductionComponent* ProdComp = WorldSubsystem->GetComponent<FSeinProductionComponent>(OwnerEntity);
	if (!ProdComp) return;
	ProdComp->bRallyToEntity = false;
	ProdComp->RallyTransform = FFixedTransform();
	ProdComp->RallyEntity = FSeinEntityHandle();
}

void USeinAbility::InitializeAbility(FSeinEntityHandle Owner, USeinWorldSubsystem* Subsystem)
{
	OwnerEntity = Owner;
	WorldSubsystem = Subsystem;
	CooldownRemaining = FFixedPoint::Zero;
	bIsActive = false;
	bCooldownStarted = false;
	DeductedCost.Amounts.Empty();
}

UWorld* USeinAbility::GetWorld() const
{
	// Skip during CDO construction — UObject systems probe GetWorld() while
	// laying out the class default object, before any subsystem is bound. The
	// nullptr return matches the UObject default for CDOs.
	if (HasAnyFlags(RF_ClassDefaultObject)) { return nullptr; }
	return WorldSubsystem ? WorldSubsystem->GetWorld() : nullptr;
}

void USeinAbility::ActivateAbility(FSeinEntityHandle Target, FFixedVector Location)
{
	// Right-click / direct-activation path — no targeter points captured.
	// Empty TargeterPoints array signals "trigger came from the smart-command
	// flow" to OnActivate; ability reads TargetLocation alone.
	TargeterPoints.Reset();
	TargetEntity = Target;
	TargetLocation = Location;
	bIsActive = true;

	// Start cooldown if the ability's timing fires on activate. OnEnd-timed abilities
	// defer cooldown until DeactivateAbility.
	if (CooldownStartTiming == ESeinCooldownStartTiming::OnActivate)
	{
		StartCooldownInternal();
	}

	// Grant each OwnedTag. Refcounting means overlapping grants
	// from BaseTags, other abilities, or effects stay present — DeactivateAbility
	// just releases our refcount.
	if (WorldSubsystem)
	{
		for (const FGameplayTag& Tag : GrantedTags)
		{
			WorldSubsystem->GrantTag(OwnerEntity, Tag);
		}
	}

	OnActivate();
}

void USeinAbility::ActivateAbilityWithTargeterPoints(FSeinEntityHandle Target, FFixedVector Location,
	const TArray<FSeinTargeterPoint>& Points)
{
	// Targeter-originated activation. TargetLocation mirrors Points[0].Location
	// when available so single-point ability OnActivate logic that only reads
	// TargetLocation continues to work — multi-target abilities iterate
	// TargeterPoints directly.
	TargeterPoints = Points;
	TargetEntity = Target;
	TargetLocation = Points.Num() > 0 ? Points[0].Location : Location;
	bIsActive = true;

	if (CooldownStartTiming == ESeinCooldownStartTiming::OnActivate)
	{
		StartCooldownInternal();
	}

	if (WorldSubsystem)
	{
		for (const FGameplayTag& Tag : GrantedTags)
		{
			WorldSubsystem->GrantTag(OwnerEntity, Tag);
		}
	}

	OnActivate();
}

void USeinAbility::TickAbility(FFixedPoint DeltaTime)
{
	if (bIsActive)
	{
		OnTick(DeltaTime);
	}
}

void USeinAbility::DeactivateAbility(bool bCancelled)
{
	if (!bIsActive)
	{
		return;
	}

	bIsActive = false;

	// Refund on cancel ─ drive DESIGN §7 Q2a / Q3c policy
	if (bCancelled && WorldSubsystem)
	{
		if (bRefundCostOnCancel && !DeductedCost.IsEmpty())
		{
			const FSeinPlayerID Owner = WorldSubsystem->GetEntityOwner(OwnerEntity);
			USeinResourceBPFL::SeinRefund(WorldSubsystem, Owner, DeductedCost);
		}
		if (bRefundCooldownOnCancel && bCooldownStarted)
		{
			CooldownRemaining = FFixedPoint::Zero;
		}
	}
	// Start cooldown on natural end when timing is OnEnd and not already running
	else if (!bCancelled && CooldownStartTiming == ESeinCooldownStartTiming::OnEnd && !bCooldownStarted)
	{
		StartCooldownInternal();
	}

	// Tear down any latent actions belonging to this ability. Without this,
	// actions like SeinMoveTo linger after EndAbility/CancelAbility and keep
	// ticking against a logically-inactive ability.
	if (WorldSubsystem && WorldSubsystem->LatentActionManager)
	{
		WorldSubsystem->LatentActionManager->CancelActionsForAbility(this);
	}

	if (WorldSubsystem)
	{
		for (const FGameplayTag& Tag : GrantedTags)
		{
			WorldSubsystem->UngrantTag(OwnerEntity, Tag);
		}
	}

	DeductedCost.Amounts.Empty();

	// Clear captured targeter points so a subsequent right-click activation
	// doesn't see stale data from the prior targeter cast.
	TargeterPoints.Reset();

	OnEnd(bCancelled);
}

void USeinAbility::EndAbility()
{
	DeactivateAbility(false);
}

void USeinAbility::CancelAbility()
{
	DeactivateAbility(true);
}

void USeinAbility::TickCooldown(FFixedPoint DeltaTime)
{
	if (CooldownRemaining > FFixedPoint::Zero)
	{
		CooldownRemaining = CooldownRemaining - DeltaTime;
		if (CooldownRemaining < FFixedPoint::Zero)
		{
			CooldownRemaining = FFixedPoint::Zero;
		}
	}
}

bool USeinAbility::IsOnCooldown() const
{
	return CooldownRemaining > FFixedPoint::Zero;
}

void USeinAbility::StartCooldownInternal()
{
	// Always set local cooldown.
	CooldownRemaining = Cooldown;
	bCooldownStarted = true;

	// Squad-scope propagation: if the activator is a squad member AND this
	// ability is squad-scope-cooldown, mirror the cooldown to every squadmate's
	// instance of this ability tag. Member-scope abilities, lone (non-squad)
	// activators, and zero-cooldown abilities all skip this branch.
	if (CooldownScope != ESeinCooldownScope::Squad) return;
	if (Cooldown <= FFixedPoint::Zero) return;
	if (!WorldSubsystem) return;

	const FSeinSquadMemberComponent* MemberData = WorldSubsystem->GetComponent<FSeinSquadMemberComponent>(OwnerEntity);
	if (!MemberData || !MemberData->SquadEntity.IsValid()) return;

	const FSeinSquadComponent* Squad = WorldSubsystem->GetComponent<FSeinSquadComponent>(MemberData->SquadEntity);
	if (!Squad) return;

	for (const FSeinSquadSlot& Slot : Squad->Slots)
	{
		const FSeinEntityHandle Mate = Slot.CurrentOccupant;
		if (!Mate.IsValid() || Mate == OwnerEntity) continue;

		const FSeinAbilityComponent* MateAC = WorldSubsystem->GetComponent<FSeinAbilityComponent>(Mate);
		if (!MateAC) continue;

		if (USeinAbility* MateInstance = MateAC->FindAbilityByTag(*WorldSubsystem, AbilityTag))
		{
			MateInstance->CooldownRemaining = Cooldown;
			MateInstance->bCooldownStarted = true;
		}
	}
}
