bool USeinAbility::ActivateAbilityInternal(FSeinEntityHandle Target,
	FFixedVector Location,
	const TArray<FSeinTargeterPoint>* Points, const FSeinAbilityActivationInputs& Inputs)
{
	if (!WorldSubsystem
		|| !WorldSubsystem->RequireStateMutationAuthorization(
			Points ? TEXT("ActivateAbilityWithTargeterPoints")
				: TEXT("ActivateAbility")))
	{
		return false;
	}
	if (bIsActive)
	{
		return false;
	}
	TStrongObjectPtr<USeinAbility> InputValues;
	const TArray<FName> InputNames = GetActivationInputNames();
	if (!InputNames.IsEmpty() || !Inputs.IsEmpty())
	{
		InputValues.Reset(NewObject<USeinAbility>(GetTransientPackage(), GetClass()));
		FString InputError;
		if (!Inputs.Decode(*InputValues, InputError)) return false;
	}
	MarkDeterministicStateDirty();
	if (!AcquireGrantedTags())
	{
		UE_LOG(LogSeinAbilityImpl, Error,
			TEXT("ActivateAbility[%s]: refused because an owned tag is saturated on %s"),
			*GetName(), *OwnerEntity.ToString());
		return false;
	}
	int64 NewActivationID = 0;
	if (!WorldSubsystem->TryAllocateAbilityActivationID(NewActivationID))
	{
		ReleaseCommittedGrantedTags();
		UE_LOG(LogSeinAbilityImpl, Error,
			TEXT("ActivateAbility[%s]: deterministic activation ID space is exhausted."),
			*GetName());
		return false;
	}

	// Publish complete runtime identity before executing designer code. This
	// makes GetActiveAbility/GetActivePassives truthful from inside OnActivate,
	// and lets synchronous EndAbility detach the exact identity immediately.
	const int64 PreviousActivationID = AbilityActivationID;
	const FSeinEntityHandle PreviousTargetEntity = TargetEntity;
	const FFixedVector PreviousTargetLocation = TargetLocation;
	const bool bPreviousCooldownStarted = bCooldownStarted;
	TArray<FSeinTargeterPoint> PreviousTargeterPoints = MoveTemp(TargeterPoints);
	if (Points)
	{
		TargeterPoints = *Points;
	}
	else
	{
		// Right-click / direct-activation path — no targeter points captured.
		// Empty means the ability should read TargetLocation alone.
		TargeterPoints.Reset();
	}
	TargetEntity = Target;
	TargetLocation = Points && Points->Num() > 0
		? (*Points)[0].Location
		: Location;
	AbilityActivationID = NewActivationID;
	bIsActive = true;
	bCooldownStarted = false;
	if (!WorldSubsystem->RegisterAbilityActivity(this))
	{
		bIsActive = false;
		AbilityActivationID = PreviousActivationID;
		TargetEntity = PreviousTargetEntity;
		TargetLocation = PreviousTargetLocation;
		TargeterPoints = MoveTemp(PreviousTargeterPoints);
		bCooldownStarted = bPreviousCooldownStarted;
		ReleaseCommittedGrantedTags();
		return false;
	}

	for (FName Name : InputNames)
	{
		FProperty* Property = FindFProperty<FProperty>(GetClass(), Name);
		Property->CopyCompleteValue(Property->ContainerPtrToValuePtr<void>(this),
			Property->ContainerPtrToValuePtr<void>(InputValues.Get()));
	}
	CooldownRecipientIDs.Reset();
	// Start cooldown if the ability's timing fires on activate. OnEnd-timed abilities
	// defer cooldown until DeactivateAbility.
	if (CooldownStartTiming == ESeinCooldownStartTiming::OnActivate)
	{
		StartCooldownInternal();
	}

	// Queue before designer callbacks so an immediate end follows activation.
	WorldSubsystem->EnqueueVisualEvent(
		FSeinVisualEvent::MakeAbilityEvent(OwnerEntity, AbilityTag, true));
	OnActivate();
	return true;
}

void USeinAbility::TickAbility(FFixedPoint DeltaTime)
{
	if (bIsActive)
	{
		// The callback is the normal Blueprint write barrier: derived Blueprint
		// variables may change even when native fields do not.
		MarkDeterministicStateDirty();
		OnTick(DeltaTime);
	}
}

void USeinAbility::DeactivateAbility(bool bCancelled)
{
	if (!WorldSubsystem
		|| !WorldSubsystem->RequireStateMutationAuthorization(TEXT("DeactivateAbility")))
	{
		return;
	}
	if (!bIsActive)
	{
		return;
	}
	MarkDeterministicStateDirty();

	bIsActive = false;
	// Detach before any refund, latent cancellation, or OnEnd callback can
	// synchronously grant/activate a replacement. The old ability may be
	// revoked and its pool slot recycled during OnEnd; pointer-validated world
	// ownership ensures it can never clear the replacement afterwards.
	WorldSubsystem->UnregisterAbilityActivity(this);
	// Queue before cleanup callbacks can activate a replacement ability.
	WorldSubsystem->EnqueueVisualEvent(
		FSeinVisualEvent::MakeAbilityEvent(OwnerEntity, AbilityTag, false));

	// Refund only the costs and cooldown writes owned by this activation.
	if (bCancelled && WorldSubsystem)
	{
		if (bRefundCostOnCancel && !DeductedCost.IsEmpty())
		{
			USeinResourceBPFL::SeinRefund(WorldSubsystem, ResourcePayer, DeductedCost);
		}
		if (bRefundCooldownOnCancel && bCooldownStarted)
		{
			RefundCooldownInternal();
		}
	}
	// Start cooldown on natural end when timing is OnEnd and not already running
	else if (!bCancelled && CooldownStartTiming == ESeinCooldownStartTiming::OnEnd && !bCooldownStarted)
	{
		StartCooldownInternal();
	}

	CooldownRecipientIDs.Reset();
	// Tear down any latent actions belonging to this ability. Without this,
	// actions like SeinMoveTo linger after EndAbility/CancelAbility and keep
	// ticking against a logically-inactive ability.
	if (WorldSubsystem && WorldSubsystem->LatentActionManager)
	{
		WorldSubsystem->LatentActionManager->CancelActionsForAbility(this);
	}

	ReleaseCommittedGrantedTags();

	DeductedCost.Amounts.Empty();
	PendingCompletionCost.Amounts.Empty();
	ResourcePayer = FSeinPlayerID::Neutral();

	// Clear captured targeter points so a subsequent right-click activation
	// doesn't see stale data from the prior targeter cast.
	TargeterPoints.Reset();

	OnEnd(bCancelled);
}

void USeinAbility::EndAbility()
{
	DeactivateAbility(false);
}

void USeinAbility::CancelAbility()
{
	DeactivateAbility(true);
}

void USeinAbility::MarkDeterministicStateDirty()
{
	if (WorldSubsystem)
	{
		WorldSubsystem->MarkAbilityRuntimeStateDirty(this);
	}
}

void USeinAbility::TickCooldown(FFixedPoint DeltaTime)
{
	if (CooldownRemaining > FFixedPoint::Zero)
	{
		MarkDeterministicStateDirty();
		CooldownRemaining = CooldownRemaining - DeltaTime;
		if (CooldownRemaining <= FFixedPoint::Zero)
		{
			CooldownRemaining = FFixedPoint::Zero;
			CooldownSourceActivationID = 0;
		}
	}
}

bool USeinAbility::IsOnCooldown() const
{
	return CooldownRemaining > FFixedPoint::Zero;
}

void USeinAbility::StartCooldownInternal()
{
	MarkDeterministicStateDirty();
	CooldownRecipientIDs.Reset();
	CooldownRemaining = Cooldown > FFixedPoint::Zero ? Cooldown : FFixedPoint::Zero;
	CooldownSourceActivationID = CooldownRemaining > FFixedPoint::Zero
		? AbilityActivationID : 0;
	bCooldownStarted = true;

	if (CooldownScope != ESeinCooldownScope::SharedGroup) return;
	if (Cooldown <= FFixedPoint::Zero) return;
	if (!WorldSubsystem || !AbilityTag.IsValid()) return;

	const FSeinBrokerMembershipData* Membership =
		WorldSubsystem->GetComponent<FSeinBrokerMembershipData>(OwnerEntity);
	if (!Membership) return;
	const FSeinEntityHandle BrokerHandle = Membership->CurrentBrokerHandle;
	const FSeinCommandBrokerData* Broker =
		WorldSubsystem->GetComponent<FSeinCommandBrokerData>(BrokerHandle);
	if (!Broker || !Broker->bSharesAbilityCooldowns
		|| !Broker->Members.Contains(OwnerEntity)) return;

	TArray<FSeinEntityHandle> Members = Broker->Members;
	Members.Sort();
	FSeinEntityHandle Previous;
	for (const FSeinEntityHandle Member : Members)
	{
		if (Member == Previous) continue;
		Previous = Member;
		if (Member == OwnerEntity || !WorldSubsystem->IsEntityAlive(Member)) continue;
		const FSeinBrokerMembershipData* MemberMembership =
			WorldSubsystem->GetComponent<FSeinBrokerMembershipData>(Member);
		if (!MemberMembership || MemberMembership->CurrentBrokerHandle != BrokerHandle) continue;
		const FSeinAbilityPayload* Abilities =
			WorldSubsystem->GetComponent<FSeinAbilityPayload>(Member);
		if (!Abilities) continue;
		if (USeinAbility* Recipient = Abilities->FindAbilityByTag(*WorldSubsystem, AbilityTag))
		{
			if (Recipient->OwnerEntity != Member) continue;
			Recipient->MarkDeterministicStateDirty();
			Recipient->CooldownRemaining = Cooldown;
			Recipient->CooldownSourceActivationID = AbilityActivationID;
			CooldownRecipientIDs.Add(Recipient->GetRuntimePoolID());
		}
	}
}

void USeinAbility::RefundCooldownInternal()
{
	// A later activation may have overwritten even our local cooldown.
	if (CooldownSourceActivationID == AbilityActivationID)
	{
		CooldownRemaining = FFixedPoint::Zero;
		CooldownSourceActivationID = 0;
	}
	for (const int32 RecipientID : CooldownRecipientIDs)
	{
		USeinAbility* Recipient = WorldSubsystem->GetAbilityInstance(RecipientID);
		if (Recipient && Recipient->CooldownSourceActivationID == AbilityActivationID)
		{
			Recipient->MarkDeterministicStateDirty();
			Recipient->CooldownRemaining = FFixedPoint::Zero;
			Recipient->CooldownSourceActivationID = 0;
		}
	}
}

TArray<FName> USeinAbility::GetActivationInputNames() const
{
	const USeinAbility* Defaults = GetClass()->GetDefaultObject<USeinAbility>();
	TArray<FName> Names = Defaults->NativeActivationInputNames;
#if WITH_EDITOR
	for (TFieldIterator<FProperty> It(GetClass(), EFieldIterationFlags::IncludeSuper); It; ++It)
	{
		if (It->GetBoolMetaData(TEXT("SeinExposeOnActivate"))) Names.AddUnique(It->GetFName());
	}
#else
	for (FName Name : Defaults->ActivationInputNames) Names.AddUnique(Name);
#endif
	Names.Sort(FNameLexicalLess());
	return Names;
}

void USeinAbility::Serialize(FArchive& Ar)
{
#if WITH_EDITOR
	if (Ar.IsSaving() && HasAnyFlags(RF_ClassDefaultObject)) ActivationInputNames = GetActivationInputNames();
#endif
	Super::Serialize(Ar);
}

